namespace Flarum\Realtime\Push\Middleware;

use Flarum\Realtime\Push\OriginSocket;
use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;
use Psr\Http\Server\MiddlewareInterface;
use Psr\Http\Server\RequestHandlerInterface;

class RememberOriginSocket implements MiddlewareInterface
{
    public const HEADER = 'X-Socket-ID';

    public function __construct(private OriginSocket $origin)
    {
    }

    public function process(ServerRequestInterface $request, RequestHandlerInterface $handler): ResponseInterface
    {
        // Restored afterwards rather than cleared: payloads are generated by
        // internal API requests, which can run inside this one on a sync queue.
        $outer = $this->origin->get();
        $this->origin->set($request->getHeaderLine(self::HEADER) ?: null);

        try {
            return $handler->handle($request);
        } finally {
            $this->origin->set($outer);
        }
    }
}
